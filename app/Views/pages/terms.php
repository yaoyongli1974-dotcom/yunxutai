            <h2>1. 账号</h2>
            <ul>
                <li>注册需提供有效邮箱并设置不少于 10 位、包含字母与数字的密码；你应该保持邮箱可用，并妥善保管密码。</li>
                <li>不转借账号。涉及逝者资料与家人共评的操作都应经由本人的账号执行。</li>
                <li>存在冒用、机器人注册或滥用平台的账号，平台可暂停或终止其使用权。</li>
            </ul>

            <h2>2. 内容规范</h2>
            <ul>
                <li>纪念馆内的生平、文章、照片与留言应与逝者相关，不得发布侮辱、诽谤、淫秽、暴力或与他人隐私相关的信息。</li>
                <li>转载他人文字与照片应经权利人同意；涉及版权的争议内容将在核实期间先行隐藏，被误伤的一方可以提交说明申诉。</li>
                <li>平台对公开内容有审核与巡查机制；馆主对留言有确认与删除权限。</li>
            </ul>

            <h2>3. 逝者身份声明与材料核验</h2>
            <p>创建纪念馆时，你须作出声明：逝者确已离去，你是其近亲，或已获家属托付。这份声明是平台允许建馆的前提，如与事实不符，平台将暂停馆面并追究相应责任。</p>
            <p>新馆默认私密。在将纪念馆设为公开或不公开收录前，馆主须提交死亡证明、官方死亡登记材料或亲属关系证明，由平台人工核验。核验通过只表示平台对“逝者身份与建馆授权”作了合理核对，不代表平台对生平内容、照片版权或家庭内部争议作出担保。材料造假或冒用他人身份的，平台将撤销核验、暂停展示并保留追责权利。</p>

            <h2>4. 禁止为在世者建馆祭奠</h2>
            <ul>
                <li>平台<b>禁止</b>为仍在世的人建立祭奠馆。一经核实，平台会暂停展示相关纪念馆，并联系创建者说明情况。</li>
                <li>发现此类情况，任何用户都可以通过纪念馆页面上的「投诉与举报」提交举报；平台核实后，将永久删除相关馆。</li>
                <li>存在争议或线索不明时，平台可先行收窄可见范围，再作处理。</li>
            </ul>

            <h2>5. 违规处理</h2>
            <p>对违规内容按程度处理：删除或隐藏内容、暂停纪念馆展示、限制账号，情节严重或涉嫌犯罪的内容移交有关部门。被处理的一方均可在详情页内补交说明，进行书面申诉。</p>

            <h2>6. 服务收费</h2>
            <p>建馆、祭奠、留言永久免费。任何需要付费的服务（照片修复、纪念视频、家族档案整理等）都会<b>事先书面明码标价</b>，并在确认订单前向你说明交付物、周期、修改次数与退款规则。未开工可全额退款；已开工按已完成进度结算。平台不售卖虚拟祭品，不自动续费，也不设置香火值、贡献值一类可用来攀比的数值与排名。</p>

            <h2>7. 服务变更与停止运营的数据处置</h2>
            <ul>
                <li>平台可能基于运营调整升级功能。涉及条款重大变动，会提前于页面公告。</li>
                <li>若平台<b>计划停止运营</b>，将提前至少 90 天公告，提供<b>全部数据的下载导出窗口</b>，并在停止后按隐私承诺删除或匿名处理剩余数据。</li>
                <li>长期保存类付费服务到期前，平台会提醒你续期或导出，到期后保留一段时间供导出，不悄悄丢弃。</li>
            </ul>

            <h2>8. 免责与适用</h2>
            <p>平台按「现状」提供服务，对不可抗力导致的临时中断不承担责任，但会尽快恢复。本条款未尽事宜按中华人民共和国既有的法律法规处理；如与法律冲突，以法律为准。</p>
