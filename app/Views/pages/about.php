    <section class="section" id="verification">
        <div class="shell">
            <div class="section-heading">
                <p class="eyebrow">身份核验</p>
                <h2>公开之前，先确认这座纪念馆应当存在</h2>
                <p class="muted" style="max-width:42em;">网络祭奠最常见的伤害，是一座未经核实的纪念馆被长期传播。我们把核验放在公开之前，而不是等举报发生后再补救。</p>
            </div>
            <div class="split">
                <div class="prose prose--page">
                    <p><strong>1. 新馆从私密开始。</strong>创建时不能选择公开，只有馆主与受邀协作者能看到内容。</p>
                    <p><strong>2. 提交可核验的材料。</strong>死亡证明或官方死亡登记、亲属关系证明、已通过的申领记录，或其他能说明身份与授权的材料；同时写清你与逝者的关系。</p>
                    <p><strong>3. 平台人工审核。</strong>管理员会核对姓名、材料出具时间与关系是否成立；无法确认的会驳回并说明需要补充什么。通过后，纪念馆才会显示「身份材料已核验」，并允许公开或进入搜索。</p>
                    <p><strong>4. 材料单独保存。</strong>核验材料不在相册里，也没有公开链接；只有授权管理员在处理时能查看，下载会留下审计记录。你可以申请删除材料，删除后核验标记失效，纪念馆回到私密。</p>
                </div>
                <aside class="notice-card">
                    <h3>这意味着什么</h3>
                    <p>未核验的纪念馆即使被直接改成公开，访客仍然看不到，列表与搜索引擎也会排除它。</p>
                    <p>发现活人被祭奠、冒用身份或虚假信息，请使用举报入口；这类举报会被标记为紧急，平台可先行暂停再核查。</p>
                    <p class="muted" style="margin-bottom:0;">核验不收取费用，也不影响基础纪念功能。</p>
                </aside>
            </div>
        </div>
