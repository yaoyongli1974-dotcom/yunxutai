                <h2>克制的原则</h2>
            </div>
            <div class="grid grid--3">
                <article class="card">
                    <h3>隐私优先</h3>
                    <p>是否公开、是否被搜索引擎收录，由馆主决定。私密馆的每张照片都经过服务端鉴权，知道链接也拿不到内容。</p>
                </article>
                <article class="card">
                    <h3>不游戏化</h3>
                    <p>献花、点烛记录次数但不排名、不升级、不提醒。比较逝者的受祭次数，不是我们理解的纪念。</p>
                </article>
                <article class="card">
                    <h3>逝者身份严肃</h3>
                    <p>创建纪念馆需要作出声明，确认逝者已经离去、你有相应权利。新馆默认私密，提交死亡证明或亲属关系材料并经人工核验后，才允许公开。</p>
                </article>
