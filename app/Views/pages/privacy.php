            <h2>2. 公开、私密与搜索引擎</h2>
            <p>纪念馆有三种可见范围：<b>公开</b>（对所有访客开放）、<b>不公开收录</b>（持有链接者可访问，搜索引擎不索引）、<b>私密</b>（仅受邀成员可见）。是否允许搜索引擎收录由馆主主动勾选，默认关闭。私密馆的照片、视频与附件均在服务端逐次鉴权，外部拿到链接无法直接下载。</p>
            <p>为降低“活人被祭奠”“冒用逝者身份”的风险，新馆默认私密；在设为公开或不公开收录前，馆主须提交死亡证明或亲属关系材料，由平台人工核验。核验材料存放于 Web 根目录之外的私有目录，仅授权审核人员可读取，不会出现在纪念馆或任何公开链接中，访问与审核都会留下审计记录。核验通过后，公开页会显示“身份材料已核验”标记。</p>

            <h2>3. 照片与其他人的权益</h2>
            <p>上传照片前，请确认你拥有相应的权利——尤其当照片中出现<b>其他在世亲友</b>时。馆主应只上传经得同意的照片，涉及在世亲友隐私的内容（住址、病历、私人联系方式等）不应出现在公开馆。如其他人对某张照片有异议，可以通过举报流程要求处理，平台会先行核查。</p>

            <h2>4. 逝者数据的权利</h2>
            <p>逝者本人无法行使个人信息权利。因此<b>馆主（创建人）声明</b>是整个体系的起点：创建时须确认逝者已离去、你有相应的亲属或受托身份。微小争议期间平台会暂停相关展示。对他人冒充直系亲属的情形，可通过举报与申诉流程纠正。</p>

            <h2>5. 导出、删除与撤回授权</h2>
            <p>在<b>我的账号 → 数据与隐私</b>可以提交：</p>
            <ul>
                <li><b>导出</b>：导出留言、祭奠记录与账号资料；</li>
                <li><b>删除</b>：删除个人内容或整个账号；</li>
                <li><b>撤回授权</b>：撤回某张照片、某段文字的公开许可。</li>
            </ul>
            <p>身份核验材料属于敏感个人信息，仅用于建馆授权核验与争议复核。你可以在账号设置中申请删除；删除后纪念馆的“已核验”标记可能失效，公开范围会回退为私密。</p>
            <p>为防止冒名操作与误删，以上申请由平台人工核验身份后处理，通常在 5 个工作日内完成，进展会通过登录邮箱回复你。存在争议期间，相关内容会先行临时隐藏。</p>

            <h2>6. 未成年人</h2>
            <p>平台不面向 14 周岁以下的用户提供注册。为已故孩童建馆时，请由家长或监护人账号代为维护，并注意不要在公开馆写出可识别的在世亲属信息。未成年人照片以家人同意为准，任何一方提出异议，我们都先将相关照片临时隐藏再核查。</p>

            <h2>7. Cookie 与会话</h2>
            <p>登录会话通过 Cookie 维持，仅用于保持在站内的登录状态与安全校验，不用于跨站跟踪；退出即失效。</p>

            <h2>8. 投诉渠道</h2>
            <p>发现姓名与地址、逝者照片被冒用或存在其他隐私问题，可：<a href="<?= e(url('/about')) ?>#reporting">按步骤提交举报</a>，或在联系方式中写明问题发送到平台邮箱。所有举报进入后台处置流程，视需要涉及内容下架、暂停或永久关闭纪念馆。</p>
